// Pixel icons on the pcstyle.dev desktop grid: 8x8 controls, 12x12 tiles.
const ICONS = {
  x: ["##....##", "###..###", ".######.", "..####..", "..####..", ".######.", "###..###", "##....##"],
  copy: ["#####...", "#...#...", "#..#####", "#..#...#", "####...#", "...#...#", "...#####", "........"],
  check: ["........", ".......#", "......##", "#....##.", "##..##..", ".####...", "..##....", "........"],
  open: ["...#####", "......##", ".....#.#", "....#..#", "...#...#", "..#.....", ".#......", "#......."],
  download: ["...##...", "...##...", "...##...", "#..##..#", ".#.##.#.", "..####..", "...##...", "########"],
  trash: ["..####..", "########", ".#....#.", ".#.#.##.", ".#.#.##.", ".#.#.##.", ".#....#.", ".######."],
  upload: ["............", ".....#......", "....#.#.....", "...#.#.#....", ".....#......", ".....#......", ".....#......", ".....#......", "............", ".#########..", "............", "............"],
  link: ["............", "............", "..####......", ".#....#.....", ".#....#.....", ".#..######..", "..####....#.", ".....#....#.", ".....#....#.", "......####..", "............", "............"],
} as const;

export type PixName = keyof typeof ICONS;

export function Pix({ name, className }: { name: PixName; className?: string }) {
  const rows = ICONS[name];
  const d = rows.flatMap((row, y) => [...row].map((c, x) => (c === "#" ? `M${x} ${y}h1v1h-1z` : ""))).join("");
  return (
    <svg className={className} viewBox={`0 0 ${rows[0].length} ${rows.length}`} aria-hidden="true">
      <path d={d} />
    </svg>
  );
}
